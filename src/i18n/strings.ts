/** Ein Problem des Kerns als Satz in der Sprache des Plugins; eine Rundennummer stellt „Runde n:“ voran. `null`-Parameter heißen „nicht gesetzt“. */
export function problemText(p: Problem): string {
  // Der Grund eines schreibgeschützten Felds ist ein Code (`ReadonlyReason`): er wird hier zum Satz.
  const params = p.code === "field-readonly" ? [p.params[0] ?? null, t(`fields.readonly.${String(p.params[1])}`)] : p.params;
  const text = t(`problem.${p.code}`, ...params.map((v) => (v === null ? t("problem.unset") : v)));
  return p.round === undefined ? text : t("problem.round", p.round, text);
}

