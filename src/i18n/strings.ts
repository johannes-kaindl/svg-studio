export const STRINGS: Record<Lang, Record<string, string>> = { en: EN, de: DE };
export const HELP_TEXTS = { en: HELP_SETTING_TEXTS_EN, de: HELP_SETTING_TEXTS_DE } as const;

/** Registriert die Texte; einmal vor dem ersten `t()` (im `onload`). */
export function initStrings(lang: Lang): void {
  defineStrings(STRINGS);
  setLang(lang);
}

/** Die Sätze der Messzeile (Kit `measured-quality`) in der Sprache des Plugins; die Zahlen kommen aus der Tabelle in `core/quality.ts`. */
/** Der sprachneutrale Zusatz einer Messzeile als Satzteil (`plans:2/3` → „, floor plans 2 of 3“); Unbekanntes bleibt weg statt unübersetzt zu erscheinen. */
function extraText(extra: string | undefined): string {
  const plans = extra === undefined ? null : /^plans:(\d+)\/(\d+)$/.exec(extra);
  return plans === null ? "" : t("quality.extra.plans", Number(plans[1]), Number(plans[2]));
}

export function qualityTexts(): QualityTexts {
  return {
    measured: (m) => t(m.task === "refine" ? "quality.measured.refine" : "quality.measured.create", m.good, m.of, extraText(m.extra), m.model, m.measuredAt),
    notMeasured: t("quality.notMeasured"),
    smallReference: (ref, short) => t("quality.smallReference", short, ref.good, ref.of),
    failureBase: (task) => t(task === "refine" ? "quality.failure.refine" : "quality.failure.create"),
    failureOwn: (m) => t("quality.failureOwn", m.good, m.of),
    failureBest: (top) => t("quality.failureBest", top.model, top.good, top.of),
    thinkingNote: t("quality.thinkingNote"),
  };
}

